#!/usr/bin/env python3
"""Report the `crate::` references that violate the crate layering.

Maps every source file to its crate (placement.toml when present, else the manifest
assignment), resolves each reference through `graph.py`, and lists references that go
to a crate which is not strictly below the referencing crate. References already
labelled by `resolve.py` (seams.json) are counted by category; any other violating
reference is a BACK-EDGE the placement does not explain. Writes `back_edges.json` and
`BACK-EDGES.md` next to this script (MEDULLA-CONTRACT-R056).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from crate_split.graph import collect_refs
from crate_split.ownership import (
    DEFAULT_MANIFEST,
    DEFAULT_PLACEMENT,
    Manifest,
    build_owner_map,
    list_src_files,
    load_manifest,
    load_placement,
)

HERE = Path(__file__).resolve().parent


@dataclass(frozen=True)
class Edge:
    from_crate: str
    to_crate: str
    file: str
    line: int
    item: str
    in_test: bool
    category: str


def owners_for(
    manifest: Manifest, files: list[str], placement: Path | None
) -> dict[str, str]:
    if placement is not None and placement.is_file():
        return load_placement(placement)
    return {f: c or "?" for f, c in build_owner_map(manifest, files).items()}


def load_labels(path: Path | None) -> dict[tuple[str, int, str], str]:
    if path is None or not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {(r["file"], r["line"], r["item"]): r["category"] for r in data["refs"]}


def violating_edges(
    manifest: Manifest, owners: dict[str, str], root: Path, labels: dict
) -> list[Edge]:
    files = list_src_files(root)
    edges = []
    for ref in collect_refs(root, files):
        src, dst = owners.get(ref.src), owners.get(ref.dst)
        if src is None or dst is None or manifest.may_depend(src, dst):
            continue
        cat = labels.get((ref.src, ref.line, ref.item), "unclassified")
        edges.append(Edge(src, dst, ref.src, ref.line, ref.item, ref.in_test, cat))
    return sorted(
        edges, key=lambda e: (e.from_crate, e.to_crate, e.file, e.line, e.item)
    )


def crate_stats(root: Path, owners: dict[str, str]) -> dict[str, dict[str, int]]:
    stats: dict[str, dict[str, int]] = defaultdict(lambda: {"files": 0, "lines": 0})
    for rel, crate in owners.items():
        path = root / rel
        if path.is_file():
            stats[crate]["files"] += 1
            stats[crate]["lines"] += len(
                path.read_text(encoding="utf-8", errors="replace").splitlines()
            )
    return dict(sorted(stats.items()))


def summarize(edges: list[Edge], stats: dict[str, dict[str, int]]) -> dict:
    cats = Counter(e.category for e in edges)
    pairs = Counter(f"{e.from_crate}->{e.to_crate}" for e in edges)
    unclassified = [asdict(e) for e in edges if e.category == "unclassified"]
    return {
        "crates": stats,
        "by_category": dict(cats.most_common()),
        "pairs": dict(pairs.most_common()),
        "unclassified_count": len(unclassified),
        "unclassified": unclassified,
    }


def render_markdown(summary: dict) -> str:
    out = [
        "# Crate-split back-edges",
        "",
        "Generated by `scripts/crate_split/edges.py`.",
        "",
    ]
    out += ["| crate | files | lines |", "|---|---|---|"]
    out += [
        f"| {n} | {s['files']} | {s['lines']} |" for n, s in summary["crates"].items()
    ]
    out += ["", "## Violating references by category", ""]
    out += [f"- {c}: {n}" for c, n in summary["by_category"].items()]
    out += ["", f"Unclassified back-edges: {summary['unclassified_count']}", ""]
    grouped: dict[tuple[str, str], Counter[str]] = defaultdict(Counter)
    for e in summary["unclassified"]:
        grouped[(e["from_crate"], e["to_crate"])][e["item"]] += 1
    for (a, b), items in sorted(grouped.items(), key=lambda kv: -sum(kv[1].values())):
        out += [f"## {a} -> {b} ({sum(items.values())})", ""]
        out += [f"- `{item}` x{n}" for item, n in items.most_common(40)] + [""]
    return "\n".join(out)


def parse_args(argv: list[str]) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, default=HERE.parents[1])
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ap.add_argument("--placement", type=Path, default=DEFAULT_PLACEMENT)
    ap.add_argument("--seams", type=Path, default=HERE / "seams.json")
    ap.add_argument("--out-dir", type=Path, default=HERE)
    return ap.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    manifest = load_manifest(args.manifest)
    owners = owners_for(manifest, list_src_files(args.root), args.placement)
    edges = violating_edges(manifest, owners, args.root, load_labels(args.seams))
    summary = summarize(edges, crate_stats(args.root, owners))
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "back_edges.json").write_text(
        json.dumps(summary, indent=1) + "\n", encoding="utf-8"
    )
    (args.out_dir / "BACK-EDGES.md").write_text(
        render_markdown(summary) + "\n", encoding="utf-8"
    )
    print(
        f"{len(edges)} violating references, "
        f"{summary['unclassified_count']} unclassified"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
