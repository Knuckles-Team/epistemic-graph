def _source_identity(commit: str) -> tuple[bytes, bytes, bytes, list[dict[str, str]]]:
    adapter = _git_bytes(["show", f"{commit}:scripts/check_dupehound_census.py"])
    wrapper = _git_bytes(["show", f"{commit}:scripts/check_dupehound.py"])
    contract = _git_bytes(["show", f"{commit}:scripts/scanner_contract.py"])
    current = {
        "adapter": digest_bytes(Path(__file__).read_bytes()),
        "wrapper": digest_bytes(Path(check_dupehound.__file__).read_bytes()),
        "contract": digest_bytes(Path(scanner_contract.__file__).read_bytes()),
    }
    selected = {
        "adapter": digest_bytes(adapter),
        "wrapper": digest_bytes(wrapper),
        "contract": digest_bytes(contract),
    }
    if selected["adapter"] != current["adapter"]:
        raise CensusError("adapter source differs from the selected candidate tree")
    if selected["wrapper"] != current["wrapper"]:
        raise CensusError(
            "changed-source wrapper differs from the selected candidate tree"
        )
    if selected["contract"] != current["contract"]:
        raise CensusError("scanner contract differs from the selected candidate tree")
    config_items = [
        {
            "scope": "repo",
            "logical_path": "scripts/check_dupehound_census.py",
            "sha256": selected["adapter"],
            "source_id": "eg-dupehound-census-adapter",
        },
        {
            "scope": "repo",
            "logical_path": "scripts/check_dupehound.py",
            "sha256": selected["wrapper"],
            "source_id": "eg-dupehound-changed-wrapper",
        },
        {
            "scope": "repo",
            "logical_path": "scripts/scanner_contract.py",
            "sha256": selected["contract"],
            "source_id": "eg-scanner-contract-loader",
        },
    ]
    return adapter, wrapper, contract, config_items


def _candidate_contract(
    commit: str, pyproject: bytes
) -> scanner_contract.ScannerContract:
    with tempfile.NamedTemporaryFile(suffix="-pyproject.toml") as contract_file:
        contract_file.write(pyproject)
        contract_file.flush()
        try:
            return scanner_contract.load_contract(Path(contract_file.name))
        except scanner_contract.ScannerContractError as exc:
            raise CensusError(f"candidate scanner contract is invalid: {exc}") from exc


def _tool_context(
    config: scanner_contract.ScannerContract,
) -> tuple[str, dict[str, Any]]:
    try:
        executable = scanner_contract.resolve_binary("dupehound", "DUPEHOUND_BIN")
    except (FileNotFoundError, OSError) as exc:
        raise CensusError(str(exc), code="tool_missing") from exc
    try:
        scanner_contract.exact_version(
            executable, config.dupehound_version_output, cwd=ROOT
        )
    except RuntimeError as exc:
        raise CensusError(str(exc), code="tool_drift") from exc
    try:
        binary_digest = digest_bytes(Path(executable).read_bytes())
    except OSError as exc:
        raise CensusError(f"could not hash dupehound binary: {exc}") from exc
    tool = _empty_tool()
    tool["version"] = config.dupehound_version
    tool["artifact"] = {
        "kind": "binary_sha256",
        "digest": binary_digest,
        "locator": f"dupehound@{config.dupehound_version}",
        "index_id": None,
        "lockfile_sha256": None,
        "trust_boundary": "runner-local-pinned-binary",
    }
    return executable, tool


def _load_context(args: argparse.Namespace) -> CandidateContext:
    if args.repository != REPOSITORY:
        raise CensusError(f"unsupported repository profile: {args.repository!r}")
    if args.profile != PROFILE_ID:
        raise CensusError(f"unsupported dupehound profile: {args.profile!r}")
    commit, tree = _resolve_candidate(args.commit)
    entries = _tree_entries(commit)
    tree_listing_sha256 = tree_listing_digest(entries)
    pyproject = _git_bytes(["show", f"{commit}:pyproject.toml"])
    _adapter, wrapper, contract_source, config_items = _source_identity(commit)
    config_items.insert(
        0,
        {
            "scope": "repo",
            "logical_path": "pyproject.toml",
            "sha256": digest_bytes(pyproject),
            "source_id": "eg-scanner-contract",
        },
    )
    config = _candidate_contract(commit, pyproject)
    profile = profile_definition(config)
    return CandidateContext(
        commit=commit,
        tree=tree,
        entries=entries,
        tree_listing_sha256=tree_listing_sha256,
        config=config,
        profile=profile,
        profile_sha256=digest_json(profile),
        universe_sha256=digest_json(universe_definition()),
        stage_policy_sha256=digest_json(stage_policy_definition()),
        config_items=config_items,
        executable=None,
        tool=_empty_tool(),
    )


def _invoke_scan(command: list[str]) -> tuple[bytes, bytes]:
    environment = scanner_contract.sanitized_env(
        base={
            **os.environ,
            "RAYON_NUM_THREADS": str(THREAD_BOUND),
            "LC_ALL": "C",
            "LANG": "C",
        }
    )
    try:
        process = subprocess.run(
            command,
            cwd=str(ROOT),
            env=environment,
            capture_output=True,
            text=False,
            timeout=SCAN_TIMEOUT_SECONDS,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise CensusError(
            f"dupehound timed out after {SCAN_TIMEOUT_SECONDS}s",
            code="timeout",
            raw=exc.stdout or b"",
            stderr=exc.stderr or b"",
        ) from exc
    except (OSError, UnicodeError) as exc:
        raise CensusError(f"could not execute dupehound: {exc}") from exc
    raw = process.stdout or b""
    stderr = process.stderr or b""
    if process.returncode != 0:
        raise CensusError(
            f"dupehound exited {process.returncode}",
            code="native_exit",
            raw=raw,
            stderr=stderr,
        )
    return raw, stderr


def _validate_native_output(
    raw: bytes,
    *,
    stderr: bytes,
    snapshot: Path,
    manifest_entries: list[ClassifiedEntry],
    expected_skip_counts: dict[str, int],
) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Join a successful native process while preserving its output on drift."""

    try:
        return validate_native_report(
            raw,
            snapshot=snapshot,
            manifest_entries=manifest_entries,
            expected_skip_counts=expected_skip_counts,
        )
    except CensusError as exc:
        raise CensusError(
            str(exc),
            code="native_report_invalid",
            raw=exc.raw or raw,
            stderr=exc.stderr or stderr,
        ) from exc


def _success_evidence(
    *,
    context: CandidateContext,
    args: argparse.Namespace,
    run_id: str,
    started_at: str,
    classified: list[ClassifiedEntry],
    manifest: dict[str, Any],
    normalized: dict[str, Any] | None,
    raw: bytes,
) -> dict[str, Any]:
    raw_ref = str(Path(args.raw_output))
    normalized_ref = str(Path(args.normalized_output))
    clusters = normalized["clusters"] if normalized is not None else []
    projection = _test_projection_metrics(clusters)
    findings = _make_findings(clusters, context.tree_listing_sha256)
    evidence = _base_envelope(
        run_id=run_id,
        started_at=started_at,
        profile=context.profile,
        universe=universe_definition(),
        stage_policy=stage_policy_definition(),
        raw_sha256=digest_bytes(raw),
        raw_ref=raw_ref,
        normalized_ref=normalized_ref,
        commit=context.commit,
        tree=context.tree,
        tree_listing_sha256=context.tree_listing_sha256,
        manifest=manifest,
        config_items=context.config_items,
        tool=context.tool,
    )
    scope = manifest["scope"]
    metric_status = (
        "not_applicable"
        if scope == "not_applicable"
        else ("findings" if findings else "clean")
    )
    evidence["run"]["profile"]["sha256"] = context.profile_sha256
    evidence["run"]["expected_universe"]["sha256"] = context.universe_sha256
    evidence["run"]["stage_policy"]["sha256"] = context.stage_policy_sha256
    evidence["result"]["scope"] = scope
    evidence["result"]["exit_class"] = (
        "clean" if scope == "applicable" else "not_applicable"
    )
    evidence["result"]["advisory_findings"] = len(findings)
    evidence["result"]["findings_by_class"]["product_debt"] = len(findings)
    evidence["result"]["metrics"] = [
        {
            "id": ALGORITHM_ID,
            "stage_policy_id": STAGE_POLICY_ID,
            "scope_kind": "full_census",
            "profile_id": PROFILE_ID,
            "algorithm": ALGORITHM_ID,
            "source_id": "dupehound.native.scan",
            "universe_id": EXPECTED_UNIVERSE_ID,
            "universe_sha256": context.universe_sha256,
            "threshold_or_policy_id": THRESHOLD_POLICY_ID,
            "status": metric_status,
            "raw_sha256": digest_bytes(raw),
            "raw_ref": str(Path(args.raw_output)),
            "normalized_sha256": None,
            "normalized_ref": normalized_ref,
        }
    ]
    evidence["findings"] = findings
    native_report = (
        _public_native_report(normalized) if normalized is not None else None
    )
    if native_report is not None:
        native_report["test_projection"] = projection
    evidence["normalized"] = {
        "candidate": {
            "commit": context.commit,
            "tree_id": context.tree,
            "tree_listing_sha256": context.tree_listing_sha256,
            "materialized_root_sha256": manifest["candidate"][
                "materialized_root_sha256"
            ],
        },
        "profile_id": PROFILE_ID,
        "native": native_report,
        "production": {
            "file_count": sum(entry.class_name == "production" for entry in classified),
            "function_count": (
                normalized["stats"]["functions"] if normalized is not None else 0
            ),
            "function_count_scope": (
                "native_production_files_including_inline_test_members"
                if normalized is not None
                else "not_applicable"
            ),
            "cluster_count": projection["production"]["cluster_count"],
            "extra_copies": projection["production"]["extra_copies"],
            "deletable_lines": projection["production"]["deletable_lines"],
            "advisory_finding_count": len(findings),
            "not_applicable_count": int(scope == "not_applicable"),
            "native_scan_executed": normalized is not None,
            "test_projection": projection["production"],
        },
        "manifest": {
            "included_count": len(manifest["included"]),
            "excluded_count": len(manifest["excluded"]),
            "source_paths_sha256": manifest["source_paths_sha256"],
            "path_class_counts": _path_counts(classified),
        },
    }
    if normalized is None:
        evidence["report"]["normalization"] = "not_applicable"
        evidence["report"]["normalization_reason"] = "empty-production-universe-v1"
    _finalize_normalized_digest(evidence)
    return evidence


def _scan_context(
    context: CandidateContext,
    args: argparse.Namespace,
    run_id: str,
    started_at: str,
) -> tuple[dict[str, Any], bytes, bytes]:
    with materialize(context.commit, context.entries) as materialized:
        classified = classify_entries(
            context.entries, materialized.contents, context.config
        )
        manifest, _ = build_manifest(
            commit=context.commit,
            tree=context.tree,
            tree_listing_sha256=context.tree_listing_sha256,
            materialized=materialized,
            entries=classified,
            profile_sha256=context.profile_sha256,
        )
        context.manifest = manifest
        if manifest["scope"] == "not_applicable":
            return (
                _success_evidence(
                    context=context,
                    args=args,
                    run_id=run_id,
                    started_at=started_at,
                    classified=classified,
                    manifest=manifest,
                    normalized=None,
                    raw=b"",
                ),
                b"",
                b"",
            )
        context.executable, context.tool = _tool_context(context.config)
        assert context.executable is not None
        command = scan_command(context.executable, materialized.root, context.config)
        context.tool["invocation"] = list(command)
        raw, stderr = _invoke_scan(command)
        normalized, _unused = _validate_native_output(
            raw,
            stderr=stderr,
            snapshot=materialized.root,
            manifest_entries=classified,
            expected_skip_counts=_native_skip_counts(classified),
        )
        evidence = _success_evidence(
            context=context,
            args=args,
            run_id=run_id,
            started_at=started_at,
            classified=classified,
            manifest=manifest,
            normalized=normalized,
            raw=raw,
        )
        return evidence, raw, stderr


def _failure_evidence(
    *,
    context: CandidateContext | None,
    args: argparse.Namespace,
    run_id: str,
    started_at: str,
    raw: bytes,
    error: CensusError,
) -> dict[str, Any]:
    evidence = _base_envelope(
        run_id=run_id,
        started_at=started_at,
        profile=context.profile if context else {"id": PROFILE_ID},
        universe=universe_definition(),
        stage_policy=stage_policy_definition(),
        raw_sha256=digest_bytes(raw),
        raw_ref=str(Path(args.raw_output)),
        normalized_ref=str(Path(args.normalized_output)),
        commit=context.commit if context else None,
        tree=context.tree if context else None,
        tree_listing_sha256=context.tree_listing_sha256 if context else None,
        manifest=context.manifest if context else None,
        config_items=context.config_items if context else [],
        tool=context.tool if context else _empty_tool(),
    )
    evidence["errors"] = [{"code": error.code, "message": str(error)}]
    evidence["report"]["normalization"] = "none"
    evidence["report"]["normalization_reason"] = "cannot-run-before-normalization"
    evidence["report"]["normalized_sha256"] = None
    return evidence


def execute(args: argparse.Namespace) -> tuple[dict[str, Any], bytes, bytes]:
    started_at = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
    run_id = str(uuid.uuid4())
    raw = b""
    stderr = b""
    context: CandidateContext | None = None
    try:
        context = _load_context(args)
        return _scan_context(context, args, run_id, started_at)
    except CensusError as exc:
        # Preserve the command output on a malformed or failing native run.
        raw = exc.raw or raw
        stderr = exc.stderr or stderr
        return (
            _failure_evidence(
                context=context,
                args=args,
                run_id=run_id,
                started_at=started_at,
                raw=raw,
                error=exc,
            ),
            raw,
            stderr,
        )


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", default=REPOSITORY)
    parser.add_argument("--commit", default="HEAD")
    parser.add_argument("--profile", default=PROFILE_ID)
    parser.add_argument("--raw-output", required=True, type=Path)
    parser.add_argument("--normalized-output", required=True, type=Path)
    parser.add_argument("--stderr-output", type=Path)
    parser.add_argument("--manifest-output", type=Path)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    stderr_output = args.stderr_output or args.raw_output.with_suffix(
        args.raw_output.suffix + ".stderr"
    )
    try:
        evidence, raw, native_stderr = execute(args)
        _write_bytes(args.raw_output, raw)
        _write_bytes(stderr_output, native_stderr)
        _write_json(args.normalized_output, evidence)
        if args.manifest_output:
            _write_json(args.manifest_output, evidence["run"]["manifest"])
    except CensusError as exc:
        # Output-path failures are already a failed operation.  Keep the
        # message concise and do not print native stderr, which can contain
        # unrelated environment details.
        print(f"dupehound census: CANNOT RUN: {exc}", file=sys.stderr)
        return 2
    if evidence["result"]["exit_class"] == "cannot_run":
        error = evidence.get("errors", [{"message": "unknown census error"}])[0]
        print(f"dupehound census: CANNOT RUN: {error['message']}", file=sys.stderr)
        return 2
    print(
        "dupehound census: complete: "
        f"{evidence['result']['advisory_findings']} advisory cluster(s); "
        f"scope={evidence['result']['scope']}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
