def _finding_id(cluster: dict[str, Any], tree_listing_sha256: str) -> str:
    subject = copy.deepcopy(cluster["_finding_subject"])
    subject["candidate_tree_sha256"] = tree_listing_sha256
    return f"{ALGORITHM_ID}:{digest_json(subject)}"


def _make_findings(
    clusters: list[dict[str, Any]], tree_listing_sha256: str
) -> list[dict[str, Any]]:
    findings: list[dict[str, Any]] = []
    for cluster in clusters:
        members = cluster["production_members"]
        if len(members) < 2:
            continue
        representative = cluster["production_representative"] or members[0]
        finding_id = _finding_id(cluster, tree_listing_sha256)
        findings.append(
            {
                "id": finding_id,
                "path": representative["path"],
                "span": {
                    "start_line": representative["start_line"],
                    "end_line": representative["end_line"],
                },
                "raw_metric": {
                    "similarity": cluster["similarity"],
                    "copies": cluster["copies"],
                    "deletable_lines": cluster["deletable_lines"],
                    "native": {
                        "copies": cluster["copies"],
                        "deletable_lines": cluster["deletable_lines"],
                        "test_only": cluster["test_only"],
                    },
                    "production_projection": {
                        "copies": cluster["production_copies"],
                        "deletable_lines": cluster["production_deletable_lines"],
                        "test_member_count": cluster["test_member_count"],
                    },
                },
                "threshold_or_policy_id": THRESHOLD_POLICY_ID,
                "classification": "product_debt",
                "actionability": "advisory",
                "owner": "epistemic-graph-maintainers",
                "disposition": "advisory-clone-cluster",
                "cluster_id": cluster["native_id"],
                "language": cluster["language"],
                "members": members,
            }
        )
    findings.sort(
        key=lambda item: (item["id"], item["path"], item["span"]["start_line"])
    )
    return findings


def _public_native_report(normalized: dict[str, Any]) -> dict[str, Any]:
    """Drop only internal finding-ID assembly fields from the receipt."""

    report = copy.deepcopy(normalized)
    for cluster in report["clusters"]:
        cluster.pop("_finding_subject", None)
    return report


def _test_projection_metrics(clusters: list[dict[str, Any]]) -> dict[str, Any]:
    """Summarize native test telemetry and the auditable product projection."""

    projected = [cluster for cluster in clusters if cluster["production_copies"] >= 2]
    return {
        "policy_id": INLINE_TEST_PROJECTION_ID,
        "native": {
            "cluster_count": len(clusters),
            "extra_copies": sum(max(0, cluster["copies"] - 1) for cluster in clusters),
            "deletable_lines": sum(cluster["deletable_lines"] for cluster in clusters),
            "test_only_cluster_count": sum(
                cluster["test_only"] for cluster in clusters
            ),
            "clusters_with_test_members": sum(
                cluster["test_member_count"] > 0 for cluster in clusters
            ),
            "test_member_count": sum(
                cluster["test_member_count"] for cluster in clusters
            ),
        },
        "production": {
            "rule": "at_least_two_native_non_test_members",
            "cluster_count": len(projected),
            "extra_copies": sum(
                max(0, cluster["production_copies"] - 1) for cluster in projected
            ),
            "deletable_lines": sum(
                cluster["production_deletable_lines"] for cluster in projected
            ),
            "mixed_cluster_count": sum(
                cluster["test_member_count"] > 0 and cluster["production_copies"] > 0
                for cluster in clusters
            ),
            "single_production_member_cluster_count": sum(
                cluster["production_copies"] == 1 for cluster in clusters
            ),
            "test_only_cluster_count": sum(
                cluster["production_copies"] == 0 for cluster in clusters
            ),
        },
    }


def _base_envelope(
    *,
    run_id: str,
    started_at: str,
    profile: dict[str, Any],
    universe: dict[str, Any],
    stage_policy: dict[str, Any],
    raw_sha256: str,
    raw_ref: str,
    normalized_ref: str,
    commit: str | None,
    tree: str | None,
    tree_listing_sha256: str | None,
    manifest: dict[str, Any] | None,
    config_items: list[dict[str, str]],
    tool: dict[str, Any],
) -> dict[str, Any]:
    source_paths = list(manifest.get("included", [])) if manifest else []
    source_paths = sorted(source_paths, key=lambda item: item["path"].encode("utf-8"))
    source_digest = (
        _source_digest(
            [
                ClassifiedEntry(
                    item["path"], "", None, None, item["class"], item["reason"], None
                )
                for item in source_paths
            ]
        )
        if source_paths
        else digest_bytes(b"")
    )
    path_counts = _path_counts(
        [
            ClassifiedEntry(
                item["path"], "", None, None, item["class"], item["reason"], None
            )
            for item in (manifest.get("entries", []) if manifest else [])
        ]
    )
    candidate = {
        "kind": "commit",
        "commit": commit,
        "tree_id": tree,
        "tree_sha256": tree_listing_sha256,
        "index_sha256": None,
        "worktree_status": "unknown",
        "proof": {
            "method": "git_tree_listing_" + "v1",
            "manifest_matches": manifest is not None,
            "head_commit_matches": commit is not None,
            "candidate_tree_matches_index": None,
            "candidate_absent_deleted": True,
            "worktree_clean": None,
        },
    }
    evidence_manifest = manifest or {
        "schema": "scanner-manifest/v1",
        "scope": "not_applicable",
        "scope_reason": "census-could-not-start",
        "stage_policy_id": STAGE_POLICY_ID,
        "scope_kind": "full_census",
        "profile_id": PROFILE_ID,
        "expected_universe_id": EXPECTED_UNIVERSE_ID,
        "expected_universe_sha256": digest_json(universe),
        "included": [],
        "excluded": [],
        "added": [],
        "deleted": [],
        "reclassified": [],
        "moves": [],
        "entries": [],
        "sha256": digest_json(
            {"scope": "not_applicable", "reason": "census-could-not-start"}
        ),
    }
    return {
        "schema": "scanner-evidence/v2",
        "run": {
            "run_id": run_id,
            "started_at": started_at,
            "repository": REPOSITORY,
            "stage": "release",
            "stage_policy": {
                "id": STAGE_POLICY_ID,
                "sha256": digest_json(stage_policy),
            },
            "scope_kind": "full_census",
            "profile": {"id": PROFILE_ID, "sha256": digest_json(profile)},
            "expected_universe": {
                "id": EXPECTED_UNIVERSE_ID,
                "sha256": digest_json(universe),
            },
            "claim": "conformance_only",
            "optimization_scorecard": {"ref": None, "sha256": None},
            "instrument": "dupehound",
            "decision": "advisory",
            "comparison": {"mode": "census"},
            "base": None,
            "candidate": candidate,
            "config": config_items,
            "tool": tool,
            "manifest": evidence_manifest,
            "inputs": [],
        },
        "result": {
            "scope": evidence_manifest["scope"],
            "exit_class": "cannot_run",
            "blocking_findings": 0,
            "advisory_findings": 0,
            "findings_by_class": {
                "product_debt": 0,
                "parser_artifact": 0,
                "flat_exhaustive": 0,
                "generated": 0,
                "feature_omission": 0,
                "unknown": 0,
            },
            "artifact_counts": {
                "parser_artifact": 0,
                "flat_exhaustive": 0,
                "generated": 0,
                "feature_omission": 0,
                "unknown": 0,
            },
            "path_class_counts": path_counts,
            "metrics": [],
            "source_paths_sha256": source_digest,
        },
        "findings": [],
        "report": {
            "source_paths": source_paths,
            "raw_sha256": raw_sha256,
            "raw_ref": raw_ref,
            "normalized_sha256": None,
            "normalized_ref": normalized_ref,
            "normalization": "canonical",
            "normalization_reason": None,
        },
        "artifact_dispositions": [],
        "exceptions": [],
        "errors": [],
    }


def _finalize_normalized_digest(evidence: dict[str, Any]) -> None:
    subject = copy.deepcopy(evidence)
    subject["report"]["normalized_sha256"] = None
    for metric in subject["result"].get("metrics", []):
        metric["normalized_sha256"] = None
    normalized_sha256 = digest_json(subject)
    evidence["report"]["normalized_sha256"] = normalized_sha256
    for metric in evidence["result"].get("metrics", []):
        metric["normalized_sha256"] = normalized_sha256


def _write_bytes(path: Path, data: bytes) -> None:
    if path.is_symlink():
        raise CensusError(f"refusing to write through symlink: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _write_json(path: Path, value: object) -> None:
    _write_bytes(path, canonical_json(value))


