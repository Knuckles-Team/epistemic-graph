class CensusError(RuntimeError):
    """A fail-closed census error with optional native process output."""

    def __init__(
        self,
        message: str,
        *,
        code: str = "cannot_run",
        raw: bytes = b"",
        stderr: bytes = b"",
    ) -> None:
        super().__init__(message)
        self.code = code
        self.raw = raw
        self.stderr = stderr


@dataclass(frozen=True)
class TreeEntry:
    path: str
    mode: str
    object_type: str
    object_sha: str

    @property
    def regular(self) -> bool:
        return self.object_type == "blob" and self.mode in {"100644", "100755"}


@dataclass(frozen=True)
class ClassifiedEntry:
    path: str
    mode: str
    object_sha: str | None
    language: str | None
    class_name: str
    reason: str
    content_sha256: str | None


@dataclass
class MaterializedTree:
    root: Path
    contents: dict[str, bytes]
    materialized_root_sha256: str
    _temporary: tempfile.TemporaryDirectory[str]

