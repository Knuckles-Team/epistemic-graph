def canonical_json(value: object) -> bytes:
    """Return the repository's compact, sorted UTF-8 JSON representation."""

    try:
        return (
            json.dumps(
                value,
                ensure_ascii=False,
                allow_nan=False,
                sort_keys=True,
                separators=(",", ":"),
            ).encode("utf-8")
            + b"\n"
        )
    except (TypeError, ValueError, UnicodeEncodeError) as exc:
        raise CensusError(f"cannot canonicalize evidence: {exc}") from exc


def digest_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def digest_json(value: object) -> str:
    return digest_bytes(canonical_json(value))


def _path_text(raw: str | bytes) -> str:
    if isinstance(raw, bytes):
        try:
            value = raw.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise CensusError("git tree contains a non-UTF-8 path") from exc
    elif isinstance(raw, str):
        value = raw
    else:
        raise CensusError("tree path is not text")
    return value


def _validate_path_text(value: str) -> str:
    if not value or "\x00" in value or "\\" in value:
        raise CensusError("tree path is empty, NUL-containing, or backslash-ambiguous")
    if any(ord(char) < 0x20 for char in value):
        raise CensusError("tree path contains a control character")
    if unicodedata.normalize("NFC", value) != value:
        raise CensusError(f"tree path is not NFC-normalized: {value!r}")
    return value


def _validate_path_shape(value: str) -> str:
    posix = PurePosixPath(value)
    windows = PureWindowsPath(value)
    if posix.is_absolute() or windows.is_absolute() or windows.drive:
        raise CensusError(f"tree path is absolute: {value!r}")
    if any(part in {"", ".", ".."} for part in posix.parts):
        raise CensusError(f"tree path has an unsafe component: {value!r}")
    normalized_path = posix.as_posix()
    if normalized_path != value:
        raise CensusError(f"tree path is not canonically slash-separated: {value!r}")
    return normalized_path


def _safe_path(raw: str | bytes) -> str:
    return _validate_path_shape(_validate_path_text(_path_text(raw)))


def _git_bytes(args: list[str], *, timeout: int = 120) -> bytes:
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=str(ROOT),
            env=scanner_contract.sanitized_env(),
            capture_output=True,
            text=False,
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise CensusError(f"could not execute git: {exc}") from exc
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", "replace").strip()[:400]
        raise CensusError(f"git {' '.join(args)} failed: {detail}")
    return result.stdout


def _resolve_candidate(ref: str) -> tuple[str, str]:
    commit = _git_bytes(["rev-parse", "--verify", f"{ref}^{{commit}}"]).decode().strip()
    if not _FULL_SHA.fullmatch(commit):
        raise CensusError("candidate commit did not resolve to a full object ID")
    tree = _git_bytes(["show", "-s", "--format=%T", commit]).decode().strip()
    if not _FULL_SHA.fullmatch(tree):
        raise CensusError("candidate commit did not resolve to a full tree ID")
    _git_bytes(["cat-file", "-e", f"{commit}^{{commit}}"])
    _git_bytes(["cat-file", "-e", f"{tree}^{{tree}}"])
    return commit, tree


def _tree_entries(commit: str) -> list[TreeEntry]:
    raw = _git_bytes(["ls-tree", "-r", "-z", "--full-tree", commit])
    entries: list[TreeEntry] = []
    seen: set[str] = set()
    for record in raw.split(b"\x00"):
        if not record:
            continue
        try:
            header, path_bytes = record.split(b"\t", 1)
            mode_bytes, type_bytes, object_bytes = header.split(b" ", 2)
            mode = mode_bytes.decode("ascii")
            object_type = type_bytes.decode("ascii")
            object_sha = object_bytes.decode("ascii")
        except (ValueError, UnicodeDecodeError) as exc:
            raise CensusError("git tree listing has a malformed record") from exc
        path = _safe_path(path_bytes)
        if path in seen:
            raise CensusError(f"git tree listing has a duplicate path: {path}")
        if not _FULL_SHA.fullmatch(object_sha):
            raise CensusError(f"git tree listing has an invalid object ID: {path}")
        seen.add(path)
        entries.append(TreeEntry(path, mode, object_type, object_sha))
    entries.sort(key=lambda entry: entry.path.encode("utf-8"))
    return entries


def tree_listing_digest(entries: list[TreeEntry]) -> str:
    records = [
        entry.path.encode("utf-8")
        + b"\x00"
        + entry.mode.encode("ascii")
        + b"\x00"
        + entry.object_sha.encode("ascii")
        + b"\n"
        for entry in sorted(entries, key=lambda item: item.path.encode("utf-8"))
    ]
    return digest_bytes(b"".join(records))


def _blob_sha(data: bytes) -> str:
    # EG currently uses SHA-1 object IDs.  Computing the Git blob preimage
    # locally avoids a per-file mutable checkout lookup and proves archive
    # bytes match the immutable tree listing.
    return hashlib.sha1(
        b"blob " + str(len(data)).encode("ascii") + b"\x00" + data
    ).hexdigest()


def _archive_member_path(raw: str) -> str:
    return _safe_path(raw)


def _archive_bytes(commit: str) -> bytes:
    try:
        archive = subprocess.run(
            ["git", "archive", "--format=tar", commit],
            cwd=str(ROOT),
            env=scanner_contract.sanitized_env(),
            capture_output=True,
            text=False,
            timeout=120,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise CensusError(f"could not materialize candidate tree: {exc}") from exc
    if archive.returncode != 0:
        detail = archive.stderr.decode("utf-8", "replace").strip()[:400]
        raise CensusError(f"git archive failed: {detail}")
    return archive.stdout


def _read_archive_file(
    member: tarfile.TarInfo,
    archive: tarfile.TarFile,
    path: str,
    entry: TreeEntry,
    seen: set[str],
) -> tuple[str, bytes]:
    if not member.isfile() or member.issym() or member.islnk():
        raise CensusError(f"archive contains a non-regular path: {path}")
    if path in seen:
        raise CensusError(f"archive contains a duplicate file: {path}")
    mode = "100755" if member.mode & 0o111 else "100644"
    if mode != entry.mode:
        raise CensusError(f"archive mode mismatch for {path}")
    source = archive.extractfile(member)
    if source is None:
        raise CensusError(f"archive file could not be read: {path}")
    data = source.read()
    if _blob_sha(data) != entry.object_sha:
        raise CensusError(f"archive bytes do not match tree blob: {path}")
    return mode, data


def _write_archive_file(root: Path, path: str, mode: str, data: bytes) -> None:
    destination = root / Path(*PurePosixPath(path).parts)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if any(
        parent.is_symlink()
        for parent in [destination.parent, *destination.parent.parents]
    ):
        raise CensusError(f"archive extraction encountered symlink traversal: {path}")
    destination.write_bytes(data)
    if mode == "100755":
        destination.chmod(0o755)


def _extract_archive_member(
    member: tarfile.TarInfo,
    archive: tarfile.TarFile,
    root: Path,
    tree_by_path: dict[str, TreeEntry],
    seen: set[str],
) -> tuple[str, bytes] | None:
    if member.isdir():
        _safe_path(member.name)
        return None
    path = _archive_member_path(member.name)
    entry = tree_by_path.get(path)
    if entry is None:
        raise CensusError(f"archive contains an unlisted file: {path}")
    if not entry.regular:
        if member.issym() or member.islnk():
            # The manifest retains the tracked non-regular path; the target
            # is never extracted or followed.
            return None
        raise CensusError(f"archive contains an unsupported non-regular path: {path}")
    mode, data = _read_archive_file(member, archive, path, entry, seen)
    _write_archive_file(root, path, mode, data)
    return path, data


def _materialized_listing(
    contents: dict[str, bytes], expected: dict[str, TreeEntry], seen: set[str]
) -> str:
    missing = sorted(set(expected) - seen)
    if missing:
        raise CensusError(f"archive omitted tracked regular path: {missing[0]}")
    listing = b"".join(
        path.encode("utf-8")
        + b"\x00"
        + expected[path].mode.encode("ascii")
        + b"\x00"
        + digest_bytes(contents[path]).encode("ascii")
        + b"\n"
        for path in sorted(contents, key=lambda value: value.encode("utf-8"))
    )
    return digest_bytes(listing)


@contextmanager
def materialize(commit: str, entries: list[TreeEntry]) -> Iterator[MaterializedTree]:
    temporary = tempfile.TemporaryDirectory(
        prefix=".dupehound-census-", dir=str(ROOT.parent)
    )
    root = Path(temporary.name)
    expected = {entry.path: entry for entry in entries if entry.regular}
    contents: dict[str, bytes] = {}
    seen: set[str] = set()
    try:
        try:
            archive = tarfile.open(
                fileobj=io.BytesIO(_archive_bytes(commit)), mode="r:"
            )
        except (tarfile.TarError, OSError) as exc:
            raise CensusError(f"candidate archive is invalid: {exc}") from exc
        tree_by_path = {entry.path: entry for entry in entries}
        with archive:
            for member in archive:
                extracted = _extract_archive_member(
                    member, archive, root, tree_by_path, seen
                )
                if extracted is not None:
                    path, data = extracted
                    contents[path] = data
                    seen.add(path)
        listing_sha256 = _materialized_listing(contents, expected, seen)
        yield MaterializedTree(root, contents, listing_sha256, temporary)
    finally:
        temporary.cleanup()


def _matching_exclusion(
    path: str, config: scanner_contract.ScannerContract
) -> str | None:
    for pattern in profile_exclusions(config):
        if scanner_contract._glob_match(path, pattern):
            return pattern
    return None


def profile_exclusions(config: scanner_contract.ScannerContract) -> list[str]:
    """Return the sorted explicit union of repo and native exclusions."""

    return sorted(set(config.exclusions).union(_NATIVE_DEFAULT_EXCLUSIONS))


def _path_class_for_exclusion(path: str) -> str:
    parts = {part.casefold() for part in PurePosixPath(path).parts}
    if parts & _VENDOR_NAMES:
        return "vendor"
    if parts & _FIXTURE_NAMES:
        return "fixture"
    if parts & _DOCUMENTATION_NAMES:
        return "documentation"
    if parts & _GENERATED_NAMES:
        return "generated"
    # The remaining explicit profile exclusions are build/cache/lock policy
    # entries.  Supported-language paths in them are generated artifacts from
    # the scanner's perspective; unsupported lockfiles are classified before
    # this function is reached.
    return "generated"


def _is_hidden(path: str) -> bool:
    return any(part.startswith(".") for part in PurePosixPath(path).parts)


def _generated_marker(text: str) -> bool:
    first_ten = "\n".join(text.splitlines()[:10]).casefold()
    return any(marker in first_ten for marker in _GENERATED_MARKERS)


def _minified(text: str) -> bool:
    lines = text.splitlines() or [text]
    # Dupehound's Rust walker measures UTF-8 byte lengths and uses integer
    # division for the average; mirror that behavior so skip counters join
    # exactly rather than approximating it with Python character counts.
    lengths = [len(line.encode("utf-8")) for line in lines]
    return max(lengths, default=0) > 2000 or sum(lengths) // len(lengths) > 300


def _entry_for_nonregular(entry: TreeEntry) -> ClassifiedEntry:
    return ClassifiedEntry(
        entry.path, entry.mode, None, None, "non_regular", "mode.non_regular", None
    )


def _entry_for_unsupported(entry: TreeEntry, content_sha: str) -> ClassifiedEntry:
    return ClassifiedEntry(
        entry.path,
        entry.mode,
        entry.object_sha,
        None,
        "unsupported",
        "language.unsupported",
        content_sha,
    )


def _classify_path(
    entry: TreeEntry,
    language: str,
    content_sha: str,
    config: scanner_contract.ScannerContract,
) -> ClassifiedEntry | None:
    exclusion = _matching_exclusion(entry.path, config)
    if exclusion is not None:
        return ClassifiedEntry(
            entry.path,
            entry.mode,
            entry.object_sha,
            language,
            _path_class_for_exclusion(entry.path),
            f"path.exclusion:{exclusion}",
            content_sha,
        )
    if check_dupehound.is_dupehound_test_path(entry.path):
        return ClassifiedEntry(
            entry.path,
            entry.mode,
            entry.object_sha,
            language,
            "test",
            "path.test",
            content_sha,
        )
    if _is_hidden(entry.path):
        return ClassifiedEntry(
            entry.path,
            entry.mode,
            entry.object_sha,
            language,
            "hidden",
            "path.hidden",
            content_sha,
        )
    return None


def _classify_content(
    entry: TreeEntry, data: bytes, language: str, content_sha: str
) -> ClassifiedEntry:
    # The native walker checks the byte size before loading content.  An
    # oversized file therefore cannot become a generated/minified counter;
    # it is omitted before content classification regardless of its prefix.
    if len(data) > MAX_FILE_BYTES:
        return ClassifiedEntry(
            entry.path,
            entry.mode,
            entry.object_sha,
            language,
            "oversize",
            "content.oversize_2mib",
            content_sha,
        )
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return ClassifiedEntry(
            entry.path,
            entry.mode,
            entry.object_sha,
            language,
            "invalid_encoding",
            "content.invalid_utf8",
            content_sha,
        )
    if _generated_marker(text):
        return ClassifiedEntry(
            entry.path,
            entry.mode,
            entry.object_sha,
            language,
            "generated",
            "content.generated_marker",
            content_sha,
        )
    if _minified(text):
        return ClassifiedEntry(
            entry.path,
            entry.mode,
            entry.object_sha,
            language,
            "minified",
            "content.minified",
            content_sha,
        )
    return ClassifiedEntry(
        entry.path,
        entry.mode,
        entry.object_sha,
        language,
        "production",
        "source.production",
        content_sha,
    )


def _classify_entry(
    entry: TreeEntry,
    contents: dict[str, bytes],
    config: scanner_contract.ScannerContract,
) -> ClassifiedEntry:
    if not entry.regular:
        return _entry_for_nonregular(entry)
    data = contents.get(entry.path)
    if data is None:
        raise CensusError(f"materialization did not provide {entry.path}")
    content_sha = digest_bytes(data)
    # Lang::from_path uses the final extension verbatim; uppercase variants
    # are outside the native language universe and must remain unsupported.
    suffix = PurePosixPath(entry.path).suffix
    language = EXTENSION_LANGUAGE.get(suffix)
    # This closed map mirrors dupehound's Lang::from_path table.  The older
    # changed-source wrapper intentionally has a narrower Python suffix set;
    # using it here would incorrectly turn native C++ ``.c++`` inputs into
    # unsupported paths.
    if language is None:
        return _entry_for_unsupported(entry, content_sha)
    path_entry = _classify_path(entry, language, content_sha, config)
    return path_entry or _classify_content(entry, data, language, content_sha)


def classify_entries(
    entries: list[TreeEntry],
    contents: dict[str, bytes],
    config: scanner_contract.ScannerContract,
) -> list[ClassifiedEntry]:
    classified = [_classify_entry(entry, contents, config) for entry in entries]
    classified.sort(key=lambda item: item.path.encode("utf-8"))
    if len({item.path for item in classified}) != len(classified):
        raise CensusError("manifest classification produced duplicate paths")
    if {item.path for item in classified} != {item.path for item in entries}:
        raise CensusError("manifest classification does not cover the tree listing")
    return classified


