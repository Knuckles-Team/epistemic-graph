#!/usr/bin/env python3
"""Run the immutable, advisory full-tree dupehound census.

The existing :mod:`check_dupehound` wrapper is deliberately a changed-source
gate.  This adapter is a separate census surface: it archives one commit,
classifies every tree entry, runs the pinned ``dupehound scan`` command over
that immutable materialization, and emits a ``scanner-evidence/v2`` receipt.
It never writes a baseline and it never turns native exit ``0`` into a claim
that a tree has no duplicate functions.

Only the standard library and the repository's checked-in scanner contract
are used.  A missing identity, malformed report, path/source mismatch, or
tool drift exits ``2`` (``cannot_run``).  A complete census exits ``0``;
clusters remain visible advisory findings in the receipt.
"""

